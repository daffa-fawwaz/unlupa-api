// SeedQuranCatalog idempotently seeds Juz 1-30 and Pages 1-604
func SeedQuranCatalog(db *gorm.DB) error {
	log.Println("🌱 Seeding Quran Catalog (30 Juz & 604 Pages)...")

	// 1. Seed Juz Catalog
	if err := db.Clauses(clause.OnConflict{DoNothing: true}).CreateInBatches(StaticJuzList, 50).Error; err != nil {
		return fmt.Errorf("failed to seed quran juz catalog: %w", err)
	}

	// 2. Seed Pages Catalog
	if err := db.Clauses(clause.OnConflict{DoNothing: true}).CreateInBatches(StaticPageList, 100).Error; err != nil {
		return fmt.Errorf("failed to seed quran page catalog: %w", err)
	}

	// 3. Verification
	var juzCount int64
	var pageCount int64
	db.Model(&entities.QuranJuzCatalog{}).Count(&juzCount)
	db.Model(&entities.QuranPageCatalog{}).Count(&pageCount)

	if juzCount != 30 {
		return fmt.Errorf("quran juz catalog count mismatch: expected 30, got %d", juzCount)
	}
	if pageCount != 604 {
		return fmt.Errorf("quran page catalog count mismatch: expected 604, got %d", pageCount)
	}

	log.Printf("✅ Quran Catalog seeded & verified successfully: %d Juz, %d Pages\n", juzCount, pageCount)
	return nil
}
